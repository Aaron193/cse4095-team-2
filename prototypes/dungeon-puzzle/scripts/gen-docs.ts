// Writes Docs/Game Content.md straight from the engine data, so the doc can never drift
// from the game. Run with `npm run docs` after changing cards, enemies, tiles or maps.
import { readFileSync, writeFileSync } from 'node:fs';
import { CARD_LIST, CARDS } from '../src/engine/cards.ts';
import { ENEMIES } from '../src/engine/enemies.ts';
import { TILE_INFO, ITEM_INFO } from '../src/engine/tiles.ts';
import { SCORE } from '../src/engine/score.ts';
import type { MapDef } from '../src/engine/types.ts';

const maps: MapDef[] = JSON.parse(readFileSync(new URL('../src/data/maps.json', import.meta.url), 'utf8'));
const out: string[] = [];
const p = (s = '') => out.push(s);
const res = (r?: Partial<Record<string, number>>) =>
  Object.entries(r ?? {}).map(([el, v]) => `${v === 0 ? 'immune' : v! > 1 ? 'weak' : 'resists'} ${el}`).join(', ') || '-';

p('# Daily Delve: Game Content');
p();
p('_Generated by `npm run docs` from the engine data. Do not edit by hand._');
p();
p('## How a run works');
p();
p('1. **Briefing.** Everyone sees the same dungeon for the day, fully revealed. You are offered 9 cards (3 Fire, 3 Frost, 3 Poison) and pick 4.');
p('2. **Delve.** Move one tile at a time. Every move, wait or card is one turn; enemies and traps then take theirs. Nothing is random.');
p('3. **Score.** Reach the stairs. Fewer moves, less time, more health and unused charges all score higher.');
p();
p('You have 10 HP and a dagger: walking into an enemy deals 1 damage. Cards have limited charges and a card that would do nothing is never spent. Most obstacles have more than one answer (a card, a crate, a detour, good timing), and every published dungeon is bot-verified to have at least two different winning card sets.');
p();
p('## Cards (30)');
for (const el of ['fire', 'frost', 'poison']) {
  p();
  p(`### ${el[0].toUpperCase() + el.slice(1)}`);
  p();
  p('| Card | Charges | Effect |');
  p('| --- | --- | --- |');
  for (const c of CARD_LIST.filter((c) => c.el === el)) p(`| ${c.name} | ${c.charges} | ${c.text} |`);
}
p();
p('## Enemies');
p();
p('| Enemy | HP | Attack | Moves | Elements | Mechanic |');
p('| --- | --- | --- | --- | --- | --- |');
for (const e of Object.values(ENEMIES)) {
  const moves = e.ai === 'guard' || e.ai === 'turret' ? 'never' : e.speed === 1 ? 'every turn' : 'every 2nd turn';
  p(`| ${e.name} | ${e.quench ? '-' : e.hp}${e.armor ? ` (armor ${e.armor})` : ''} | ${e.atk} | ${moves} | ${e.quench ? 'only frost' : res(e.res)} | ${e.desc} |`);
}
p();
p('Status effects: **Burn** (1 damage a turn), **Poison** (N damage, then N-1, ... ignores armor), **Frozen** (cannot act, can be shoved; Fire thaws), **Asleep** (cannot act until damaged), **Weak** (-2 attack).');
p();
p('## Obstacles and terrain');
p();
p('| Tile | What it does |');
p('| --- | --- |');
for (const t of Object.values(TILE_INFO)) if (t.obstacle) p(`| ${t.name} | ${t.desc} |`);
for (const k of ['crate', 'potion', 'key', 'gold', 'chest']) p(`| ${ITEM_INFO[k].name} | ${ITEM_INFO[k].desc} |`);
p();
p('## Score formula');
p();
p('| Part | Points |');
p('| --- | --- |');
p(`| Clear | ${SCORE.clear} for reaching the exit; otherwise up to ${SCORE.partial} for how close you got |`);
p(`| Moves | ${SCORE.moves} x min(${SCORE.movesCap}, par / your moves) |`);
p(`| Time | ${SCORE.time} at ${SCORE.timeFull / 60}:00 or faster, falling evenly to 0 at ${SCORE.timeZero / 60}:00 |`);
p(`| Health | ${SCORE.hp} per HP left |`);
p(`| Thrift | ${SCORE.charge} per unused card charge (max ${SCORE.chargeCap}) |`);
p(`| Gold | ${SCORE.gold} per gold (max ${SCORE.goldCap}) |`);
p(`| Style | ${SCORE.style} per combo or trick kill, ${SCORE.kill} per kill (max ${SCORE.styleCap}) |`);
p();
p('Moves, Time, Health and Thrift only count if you clear. **Par** is the best run the solver bot found. Leaderboard order: cleared, then score, then fewer moves, then earlier submission. Everything except Time is re-simulated from the replay code.');
p();
p(`## The map book (${maps.length} dungeons)`);
p();
p('Each dungeon passed the bot gate: unbeatable with no cards, beatable with all of them, at least two winning card sets with no card in common to all, and a bounded share of winning loadouts. "Winning loadouts" is the share of the 126 possible 4-card picks the bot can clear with.');
p();
p('| # | Name | Par | Winning loadouts | Smallest winning card sets | Creatures |');
p('| --- | --- | --- | --- | --- | --- |');
for (const m of maps) {
  const sets = m.answers!.slice(0, 4).map((a) => a.cards.map((c) => CARDS[c].name).join(' + ')).join('; ') + (m.answers!.length > 4 ? `; +${m.answers!.length - 4} more` : '');
  const creatures = [...new Set(m.enemies.map((e) => ENEMIES[e.type].name))].join(', ');
  p(`| ${m.id + 1} | ${m.name} | ${m.par} | ${m.winPct}% | ${sets} | ${creatures} |`);
}
p();
writeFileSync(new URL('../Docs/Game Content.md', import.meta.url), out.join('\n'));
console.log(`Docs/Game Content.md written (${out.length} lines)`);
